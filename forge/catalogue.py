"""Build Catalogue/: per-collection markdown indexes + labelled thumbnail contact sheets.

  .venv/Scripts/python forge/catalogue.py            # everything
  .venv/Scripts/python forge/catalogue.py Vehicles   # one collection
"""
import sys
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).parent))
import forge  # noqa: E402

OUT = forge.ROOT / "Catalogue"
TILE, COLS, PER_SHEET = 128, 8, 48


def thumb(key):
    m = forge.Model()
    m.add(key)
    try:
        return key, forge.render(m.assemble(), None, TILE, "iso", bg="#34363D")
    except Exception as e:  # empty meshes etc.
        return key, None


def prefix(t):
    t = t.replace("%", "")
    for sep in ("_", "-"):
        if sep in t:
            return t.split(sep)[0]
    import re
    m = re.match(r"[a-z]+", t)
    return m.group(0) if m else t


def build_collection(name, blocks, pool):
    keys = [f"{name}/{b['type']}" for b in blocks]
    thumbs = dict(pool.map(thumb, keys, chunksize=8))
    # drop a prefix shared by every block (e.g. "Spacestation_") so labels stay distinctive
    import os
    common = os.path.commonprefix([b["type"] for b in blocks]) if len(blocks) > 1 else ""
    common = common[:max(common.rfind("_"), common.rfind(" ")) + 1]
    font = ImageFont.load_default()
    sheets = []
    for s in range(0, len(keys), PER_SHEET):
        chunk = keys[s:s + PER_SHEET]
        rows = (len(chunk) + COLS - 1) // COLS
        sheet = Image.new("RGBA", (COLS * TILE, rows * (TILE + 14)), (24, 25, 29, 255))
        d = ImageDraw.Draw(sheet)
        for i, k in enumerate(chunk):
            x, y = (i % COLS) * TILE, (i // COLS) * (TILE + 14)
            if thumbs[k] is not None:
                sheet.paste(thumbs[k], (x, y))
            label = k.split("/", 1)[1][len(common):]
            label = label if len(label) <= 21 else "…" + label[-20:]
            d.text((x + 3, y + TILE), label, fill=(220, 220, 225), font=font)
        fn = OUT / "sheets" / f"{name}_{s // PER_SHEET + 1}.png"
        fn.parent.mkdir(parents=True, exist_ok=True)
        sheet.convert("RGB").save(fn)
        sheets.append(fn.name)

    groups = defaultdict(list)
    for b in blocks:
        groups[prefix(b["type"])].append(b)
    kind = blocks[0]["kind"]
    lines = [f"# {name}", "",
             f"{len(blocks)} blocks ({'built-in' if kind == 'builtin' else 'custom OBJ collection'}). "
             f"Reference as `{name}/<type>`. Sizes are in Asset Forge units (x width, y height, z depth; "
             f"front = +z in AF space). Deluxe-only blocks (`%`) are excluded.", "",
             (f"Sheet labels omit the shared prefix `{common}`. " if common else "") +
             "Contact sheets (iso view, in listing order): " + ", ".join(f"[{s}](sheets/{s})" for s in sheets), ""]
    for g in sorted(groups):
        lines += [f"## {g}", "", "| type | size x,y,z | min y | slots |", "|---|---|---|---|"]
        for b in groups[g]:
            size = ", ".join(f"{h - l:.2f}" for l, h in zip(b["min"], b["max"]))
            slots = " + ".join(s.split("-", 1)[-1] if kind == "custom" else s for s in b["slots"])
            lines.append(f"| `{b['type']}` | {size} | {b['min'][1]:.2f} | {slots} |")
        lines.append("")
    (OUT / f"{name}.md").write_text("\n".join(lines), encoding="utf-8")
    return len(blocks), groups.keys()


def main():
    lib = forge.library()["blocks"]
    by_col = defaultdict(list)
    for b in lib.values():
        if not b["deluxe"]:
            by_col[b["collection"]].append(b)
    only = sys.argv[1:]
    OUT.mkdir(exist_ok=True)
    summary = []
    with ProcessPoolExecutor() as pool:
        for name in sorted(by_col, key=str.lower):
            if only and name not in only:
                continue
            n, groups = build_collection(name, by_col[name], pool)
            summary.append((name, by_col[name][0]["kind"], n, sorted(groups)))
            print(name, n)
    if not only:
        lines = ["# Block catalogue", "",
                 "Generated by `forge/catalogue.py`. Each collection page lists every block with its size and "
                 "material slots, grouped by name prefix, and links contact sheets for visual lookup.", "",
                 "| collection | kind | blocks | part families |", "|---|---|---|---|"]
        for name, kind, n, groups in summary:
            fam = ", ".join(groups[:18]) + (" …" if len(groups) > 18 else "")
            lines.append(f"| [{name}]({name}.md) | {kind} | {n} | {fam} |")
        (OUT / "README.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
